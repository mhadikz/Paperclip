import Foundation
import AppKit

/// Polls the general pasteboard and reports new content. Respects the de-facto standard
/// pasteboard flags that password managers set so secrets are never recorded.
final class ClipboardMonitor: ClipboardMonitoring {
    var onNewContent: ((CapturedContent, String?, String?) -> Void)?

    private var timer: Timer?
    private var lastChangeCount: Int = NSPasteboard.general.changeCount
    private let pollInterval: TimeInterval = 0.35
    private let maxRichTextBytes = 512 * 1024

    /// http://nspasteboard.org — set by 1Password, Keychain-style apps, and tools that
    /// write temporary data to the pasteboard.
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type"
    ]

    func start() {
        stop()
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: pollInterval, repeats: true) { [weak self] _ in
            self?.checkPasteboard()
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func ignoreCurrentChange() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    private func checkPasteboard() {
        let pasteboard = NSPasteboard.general
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        if !types.isDisjoint(with: Self.skipTypes) {
            return
        }

        let app = NSWorkspace.shared.frontmostApplication
        let bundleID = app?.bundleIdentifier
        let appName = app?.localizedName

        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            onNewContent?(.files(urls), bundleID, appName)
            return
        }

        let string = pasteboard.string(forType: .string)
        let hasImage = types.contains(NSPasteboard.PasteboardType.png.rawValue)
            || types.contains(NSPasteboard.PasteboardType.tiff.rawValue)
            || types.contains("public.jpeg")
            || types.contains("public.heic")

        // Spreadsheets and rich editors put an image *and* text on the pasteboard; the text is
        // what the user meant. A lone URL next to image data (browser "Copy Image") is not.
        if hasImage, Self.prefersImage(over: string) {
            captureImage(from: pasteboard, bundleID: bundleID, appName: appName)
            return
        }

        if let string, !string.isEmpty {
            var rtf: Data?
            if types.contains(NSPasteboard.PasteboardType.rtf.rawValue),
               let data = pasteboard.data(forType: .rtf), data.count <= maxRichTextBytes {
                rtf = data
            }
            onNewContent?(.text(string, richText: rtf), bundleID, appName)
            return
        }

        if hasImage {
            captureImage(from: pasteboard, bundleID: bundleID, appName: appName)
        }
    }

    static func prefersImage(over string: String?) -> Bool {
        guard let string else { return true }
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.isEmpty { return true }
        return ClipItem.inferType(from: trimmed) == .link
    }

    private func captureImage(from pasteboard: NSPasteboard, bundleID: String?, appName: String?) {
        if let png = pasteboard.data(forType: .png), !png.isEmpty {
            onNewContent?(.image(png), bundleID, appName)
            return
        }
        // TIFF/other representations are converted off the main thread.
        let raw: Data? = pasteboard.data(forType: .tiff)
            ?? pasteboard.data(forType: NSPasteboard.PasteboardType("public.jpeg"))
            ?? pasteboard.data(forType: NSPasteboard.PasteboardType("public.heic"))
        guard let raw, !raw.isEmpty else { return }
        let handler = onNewContent
        Task.detached(priority: .userInitiated) {
            guard let png = ImageTranscoder.pngData(from: raw) else { return }
            await MainActor.run {
                handler?(.image(png), bundleID, appName)
            }
        }
    }

    deinit {
        timer?.invalidate()
    }
}

enum ImageTranscoder {
    /// Re-encodes any ImageIO-readable data as PNG.
    static func pngData(from data: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return nil }
        let out = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(out, "public.png" as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination) else { return nil }
        return out as Data
    }

    /// Downscaled CGImage for thumbnails (longest side ≤ `maxPixelSize`).
    static func thumbnail(from url: URL, maxPixelSize: Int) -> CGImage? {
        guard let source = CGImageSourceCreateWithURL(url as CFURL, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixelSize
        ]
        return CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary)
    }
}
